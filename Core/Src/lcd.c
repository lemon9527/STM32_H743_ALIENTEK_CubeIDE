/* Physical framebuffer dimensions */
#define LCD_PHYS_W  800
#define LCD_PHYS_H  480

/**
 * @brief  Convert logical portrait coords to physical landscape coords
 *         Rotate 90 degrees clockwise: phys(x,y) = (479-log_y, log_x)
 */
static inline void lcd_rotate_coords(uint16_t log_x, uint16_t log_y, uint16_t *phys_x, uint16_t *phys_y)
{
    /* 90-degree counter-clockwise: phys_x = log_y, phys_y = phys_H - 1 - log_x */
    *phys_x = log_y;
    *phys_y = LCD_PHYS_H - 1 - log_x;
}

/**
 * @brief  Initialize LCD backlight
 */
void LCD_Init(void)
{
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_5, GPIO_PIN_SET);
}

/**
 * @brief  Fill entire screen using DMA2D (hardware accelerated, instant)
 */
void LCD_Clear(uint16_t color)
{
    uint32_t color32 = ((uint32_t)color << 16) | color;

    /* Switch DMA2D to R2M (Register-to-Memory) mode */
    hdma2d.Init.Mode = DMA2D_R2M;
    hdma2d.Init.OutputOffset = LCD_FB_STRIDE - LCD_PHYS_W;  /* stride - width = 800 */
    HAL_DMA2D_Init(&hdma2d);

    /* Fill entire physical framebuffer */
    HAL_DMA2D_Start(&hdma2d, color32, (uint32_t)lcd_framebuf, LCD_PHYS_W, LCD_PHYS_H);
    HAL_DMA2D_PollForTransfer(&hdma2d, 10);

    /* Restore M2M_PFC mode for future use */
    hdma2d.Init.Mode = DMA2D_M2M_PFC;
    hdma2d.Init.OutputOffset = 0;
    HAL_DMA2D_Init(&hdma2d);
}

/**
 * @brief  Fill a rectangle (portrait coords, rotated to physical)
 */
void LCD_Fill(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1, uint16_t color)
{
    uint16_t x, y;
    for (y = y0; y <= y1; y++)
    {
        for (x = x0; x <= x1; x++)
        {
            LCD_DrawPixel(x, y, color);
        }
    }
}

/**
 * @brief  Draw a single pixel (portrait coords, rotated to physical)
 */
void LCD_DrawPixel(uint16_t x, uint16_t y, uint16_t color)
{
    uint16_t px, py;
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;
    lcd_rotate_coords(x, y, &px, &py);
    lcd_framebuf[py * LCD_FB_STRIDE + px] = color;
}

/**
 * @brief  Draw a 2x scaled ASCII character (8x16 font -> 16x32 on screen)
 */
