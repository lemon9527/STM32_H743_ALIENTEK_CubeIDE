{
    uint8_t row, col, sy, sx;
    uint8_t idx;

    if (ch < 0x20 || ch > 0x7E) ch = ' ';
    idx = (uint8_t)(ch - 0x20);

    for (row = 0; row < 16; row++)
    {
        uint8_t line = lcd_font_8x16[idx][row];
        for (col = 0; col < 8; col++)
        {
            uint16_t pixel_color = (line & (0x80 >> col)) ? color : bg_color;
            /* Draw 2x2 block */
            for (sy = 0; sy < LCD_FONT_SCALE; sy++)
            {
                for (sx = 0; sx < LCD_FONT_SCALE; sx++)
                {
                    LCD_DrawPixel(x + col * LCD_FONT_SCALE + sx,
                                  y + row * LCD_FONT_SCALE + sy,
                                  pixel_color);
                }
            }
        }
    }
}

/**
 * @brief  Draw a string (2x scaled, portrait mode, auto line wrap)
 */
void LCD_ShowString(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg_color)
{
    uint16_t cx = x, cy = y;
    const int char_w = 8 * LCD_FONT_SCALE;   /* 16 px */
    const int char_h = 16 * LCD_FONT_SCALE;  /* 32 px */

    while (*str)
    {
        if (*str == '\r')
        {
            cx = x;
            str++;
            continue;
        }
        if (*str == '\n')
        {
            cx = x;
            cy += char_h;
            str++;
            continue;
        }
        if (cx + char_w > LCD_WIDTH)
        {
            cx = x;
            cy += char_h;
        }
        if (cy + char_h > LCD_HEIGHT) break;

        LCD_ShowCharScaled(cx, cy, *str, color, bg_color);
        cx += char_w;
        str++;
    }
}